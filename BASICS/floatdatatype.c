#include <stdio.h>

int main()
{
    /*
     Arithmetic operations on float data type
    like '+' , '-' , '*' , '/'
     */
    float x = 5; // float is used for decimal values!
    float y = 2;
    printf("%f\n", x + y);
    printf("%f\n", x - y);
    printf("%f\n", x * y);
    printf("%f\n", x / y); 

    float z = 5/2;
    printf("%f\n",z);


    float k = 5.0/2;
    printf("%f\n",k);


    float s = 5/2.0;
    printf("%f\n",s);



    return 0;
}