// ===============================
// Decision Making Statements
// ===============================
//
// Definition:
// Decision making statements allow a program to execute
// different blocks of code based on a condition.
//
// If the condition is TRUE,
//     → One block executes.
//
// If the condition is FALSE,
//     → Another block executes (or no block executes).
//
// Common Decision Making Statements:
// • if
// • if...else
// • nested if
// • else if ladder
// • switch
//
// Example:
// If marks >= 40
//     Print "Pass"
// Else
//     Print "Fail"